import os from "node:os";
import path from "node:path";

import { defineConfig, devices } from "@playwright/test";

/**
 * End-to-end checks in frontend/e2e (P2.10: accessibility and the keyboard-only reserve flow; docs/accessibility.md).
 *
 * They run against a site that is already up: the production build (next start) in front of the API on a seeded
 * throwaway database, as the frontend-quality CI job starts it. Nothing here starts a server or touches a database
 * other than through the site's own /api. Settings, all from the environment:
 *   NEARSHOP_E2E_BASE_URL     the site (default http://127.0.0.1:3000)
 *   NEARSHOP_E2E_LANGUAGES    comma-separated interface languages, one project each (default "en"; the workflow
 *                             lists them, and P7.10 adds Kannada)
 *   NEARSHOP_DEMO_PASSWORD    the seeded demo accounts' password, generated by the CI job for its run
 *   NEARSHOP_E2E_CHANNEL      optional browser channel, such as "chrome" to use an installed Google Chrome locally
 *                             instead of Playwright's own Chromium
 *   NEARSHOP_E2E_OUTPUT_DIR   where the report, traces and screenshots go: outside the repository by default
 *                             (the system's temporary folder), so a run leaves nothing to commit
 *   NEARSHOP_E2E_AXE_SUMMARY  optional file the accessibility spec appends one JSON line per audited screen to
 */
const baseURL = process.env.NEARSHOP_E2E_BASE_URL || "http://127.0.0.1:3000";
const languages = (process.env.NEARSHOP_E2E_LANGUAGES || "en")
  .split(",")
  .map((l) => l.trim())
  .filter(Boolean);
const channel = process.env.NEARSHOP_E2E_CHANNEL || undefined;
const output = process.env.NEARSHOP_E2E_OUTPUT_DIR || path.join(os.tmpdir(), "nearshop-e2e");

export type E2EOptions = { language: string };

export default defineConfig<E2EOptions>({
  testDir: "./e2e",
  outputDir: path.join(output, "results"),
  // The specs share one seeded database and sign in as the same demo accounts: run them one at a time.
  workers: 1,
  fullyParallel: false,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 1 : 0,
  timeout: 60_000,
  expect: { timeout: 10_000 },
  reporter: [
    ["list"],
    ["html", { open: "never", outputFolder: path.join(output, "report") }],
    ...(process.env.CI ? [["github"] as ["github"]] : []),
  ],
  use: {
    baseURL,
    // The customers' phones: an entry-level Android phone at 360 by 800 CSS pixels (plan section 8.15).
    ...devices["Galaxy S9+"],
    viewport: { width: 360, height: 800 },
    deviceScaleFactor: 2,
    browserName: "chromium",
    channel,
    trace: "retain-on-failure",
    screenshot: "only-on-failure",
  },
  projects: languages.map((language) => ({
    name: language,
    use: { language, locale: `${language}-IN` },
  })),
});
